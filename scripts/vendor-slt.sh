#!/usr/bin/env bash
# Builds the SpicyLyricTranslator fork (Iceni) and installs it into extensions/.
#
# Why a fork: upstream's manifest points at loader/SLT-loader.js, which fetches
# code from 7xeh.dev, injects it, and runs a 30-minute hotfix check that can
# reload Spotify. The fork drops the loader and the updater; everything is
# built locally.
#
# To pull upstream changes (inside the fork):
#   git fetch upstream && git rebase upstream/main
# Iceni's changes are kept as a small set of commits, so conflicts stay manageable.

set -euo pipefail

# sha256 differs by platform: macOS ships shasum, most Linux ships sha256sum,
# Git Bash on Windows may have either.
sha256_of() {
  if command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1" | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | awk '{print $1}'
  else echo "no sha256 tool found" >&2; return 1; fi
}

cd "$(dirname "$0")/.."
THEME_DIR="$PWD"

# Default to a sibling checkout, then the original location. Override with
# SLT_FORK on a machine that keeps it somewhere else.
if [ -n "${SLT_FORK:-}" ]; then FORK="$SLT_FORK"
elif [ -d "$THEME_DIR/../slt-iceni" ]; then FORK="$THEME_DIR/../slt-iceni"
else FORK="$HOME/other-projects/slt-iceni"; fi
LOCK="vendor.lock"
OUT="extensions/spicy-lyric-translater.js"

[ -d "$FORK" ] || { echo "Fork not found: $FORK  (override with SLT_FORK)" >&2; exit 1; }

echo "Building: $FORK"
cd "$FORK"
[ -d node_modules ] || npm install --no-audit --no-fund
npm run build

SHA=$(sha256_of dist/spicy-lyric-translater.js)
VERSION=$(node -p "require('./package.json').version")
COMMIT=$(git rev-parse HEAD)
UPSTREAM=$(git rev-parse upstream/main 2>/dev/null || echo "unknown")

cd "$THEME_DIR"
{
  echo "// Built from the Iceni fork -- generated by scripts/vendor-slt.sh"
  echo "// Source: $FORK"
  echo "// Version: $VERSION  commit: $COMMIT"
  echo "// DO NOT EDIT. Change the fork and re-run this script."
  cat "$FORK/dist/spicy-lyric-translater.js"
} > "$OUT"

touch "$LOCK"
grep -v '^slt\.' "$LOCK" > "$LOCK.tmp" || true
{
  cat "$LOCK.tmp"
  echo "slt.version=$VERSION"
  echo "slt.sha256=$SHA"
  echo "slt.fork-commit=$COMMIT"
  echo "slt.upstream-commit=$UPSTREAM"
  echo "slt.source=$FORK"
} | grep -v '^$' | sort > "$LOCK"
rm -f "$LOCK.tmp"

echo "OK  $OUT  ($(wc -c < "$OUT" | tr -d ' ') bytes)"
echo "To apply: spicetify apply"
